#!/usr/bin/env python3
"""Build-time PNG -> pinned 16-color RGB565 row-RLE; no guest image engine.

Normal --check uses stdlib only. --generate/--regenerate-check require the
existing pinned Pillow12.3.0 host tool. No network, second guest framebuffer,
runtime PNG decoder or mutable palette is introduced.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'shell/assets/wallpaper'
MANIFEST = ASSETS / 'PROVENANCE.json'
OUTPUT = ROOT / 'shell/src/wallpaper_assets.rs'
WIDTH, HEIGHT, COLORS = 240, 320, 16


def require(condition, message):
    if not condition:
        raise ValueError(message)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def pack_rows(indices):
    require(len(indices) == WIDTH * HEIGHT, 'wallpaper pixel count')
    data, offsets = bytearray(), [0]
    for row in range(HEIGHT):
        x = 0
        while x < WIDTH:
            value = indices[row * WIDTH + x]
            require(0 <= value < COLORS, 'wallpaper palette index')
            start = x
            while x < WIDTH and x - start < 16 and indices[row * WIDTH + x] == value:
                x += 1
            data.append(((x - start - 1) << 4) | value)
        offsets.append(len(data))
    require(len(data) < 32768, 'wallpaper encoded budget')
    return bytes(data), offsets


def unpack_rows(data, offsets):
    """Bounded independent format validation, also used for corrupt-input tests."""
    require(len(offsets) == HEIGHT + 1 and offsets[0] == 0
            and offsets[-1] == len(data) and 0 < len(data) < 32768, 'row table/data extent')
    decoded = bytearray()
    for start, end in zip(offsets, offsets[1:]):
        require(0 <= start < end <= len(data) and end - start <= WIDTH, 'row offsets')
        row = bytearray()
        for value in data[start:end]:
            row.extend([value & 15] * ((value >> 4) + 1))
            require(len(row) <= WIDTH, 'row overflow')
        require(len(row) == WIDTH, 'short row')
        decoded.extend(row)
    require(len(decoded) == WIDTH * HEIGHT, 'decoded extent')
    return bytes(decoded)


def rgb565(red, green, blue):
    return ((red & 0xf8) << 8) | ((green & 0xfc) << 3) | (blue >> 3)


def darken(value):
    return (((value >> 11) * 3 // 4) << 11
            | (((value >> 5) & 63) * 3 // 4) << 5 | ((value & 31) * 3 // 4))


def raster(manifest):
    import PIL
    from PIL import Image
    require(PIL.__version__ == manifest['toolchain']['pillow'] == '12.3.0', 'pinned Pillow version')
    with Image.open(ASSETS / manifest['source']['path']) as source:
        require(source.format == 'PNG' and source.size == (1086, 1448), 'source PNG geometry/type')
        image = source.convert('RGB').resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
    image = image.quantize(colors=COLORS, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    indices = image.tobytes()
    palette = image.getpalette()[:COLORS * 3]
    values = [rgb565(*palette[index:index + 3]) for index in range(0, COLORS * 3, 3)]
    data, offsets = pack_rows(indices)
    require(unpack_rows(data, offsets) == indices, 'row RLE round trip')
    values += [darken(value) for value in values]
    raw = b''.join(struct.pack('<H', values[index]) for index in indices)
    return values, offsets, data, raw


def rust_source(palette, offsets, data):
    def rows(values, width, formatter):
        return '\n'.join('    ' + ', '.join(formatter(value) for value in values[start:start + width]) + ','
                         for start in range(0, len(values), width))
    return ('''// @generated by shell/tools/generate_wallpaper.py; do not edit.
// Project Crosshair generated landscape; source/prompt/provenance in shell/assets/wallpaper/.
// 240x320, 16 RGB565 colors plus dark palette; row-local (length-1):4/index:4 RLE.
pub const WIDTH: u16 = 240;
pub const HEIGHT: u16 = 320;
pub const PAYLOAD_BYTES: usize = ''' + str(len(data) + len(offsets) * 2 + len(palette) * 2) + ''';
pub static PALETTE: [u16; 32] = [
''' + rows(palette, 8, lambda v: f'0x{v:04x}') + '''
];
pub static ROW_OFFSETS: [u16; 321] = [
''' + rows(offsets, 12, str) + '''
];
pub static DATA: [u8; ''' + str(len(data)) + '''] = [
''' + rows(data, 20, lambda v: f'0x{v:02x}') + '''
];
''').encode()


def parse_generated(raw):
    def values(name, kind):
        match = re.search(rb'pub static ' + name + rb': \[' + kind + rb'; [0-9]+\] = \[\n(.*?)\n\];', raw, re.S)
        require(match is not None, 'generated array ' + name.decode())
        content = match[1]
        tokens = re.findall(rb'0x[0-9a-f]+|[0-9]+', content)
        require(re.sub(rb'0x[0-9a-f]+|[0-9]+|[\s,]', b'', content) == b'', 'generated array syntax')
        return [int(value, 0) if value.startswith(b'0x') else int(value) for value in tokens]
    palette, offsets, data = values(b'PALETTE', b'u16'), values(b'ROW_OFFSETS', b'u16'), values(b'DATA', b'u8')
    require(len(palette) == 32 and all(0 <= v <= 65535 for v in palette), 'palette extent')
    require(all(0 <= v <= 255 for v in data), 'data byte')
    unpack_rows(bytes(data), offsets)
    return palette, offsets, bytes(data)


def inputs():
    manifest = json.loads(MANIFEST.read_text())
    require(manifest['schema'] == 'crosshair-wallpaper-v1'
            and manifest['width'] == WIDTH and manifest['height'] == HEIGHT
            and manifest['colors'] == COLORS, 'wallpaper manifest')
    require(manifest['source']['path'] == 'crosshair-mist-source.png', 'source path')
    for entry in (manifest['source'], manifest['prompt']):
        require(entry['path'] in ('crosshair-mist-source.png', 'PROMPT.txt'), 'asset path')
        raw = (ASSETS / entry['path']).read_bytes()
        require(len(raw) == entry['bytes'] and digest(raw) == entry['sha256'], 'source/prompt binding')
    return manifest


def check(manifest):
    require(digest(Path(__file__).read_bytes()) == manifest['generator_sha256'], 'generator binding')
    raw = OUTPUT.read_bytes()
    require(digest(raw) == manifest['generated_sha256'], 'generated Rust binding')
    palette, offsets, data = parse_generated(raw)
    payload = struct.pack('<32H', *palette) + struct.pack('<321H', *offsets) + data
    require(len(payload) == manifest['payload_bytes'] and digest(payload) == manifest['payload_sha256'], 'payload binding')
    indices = unpack_rows(data, offsets)
    pixels = b''.join(struct.pack('<H', palette[index]) for index in indices)
    require(digest(pixels) == manifest['raw565_sha256'], 'RGB565 output binding')
    require(rust_source(palette, offsets, data) == raw, 'canonical generated Rust')


def main():
    parser = argparse.ArgumentParser(__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--generate', action='store_true')
    mode.add_argument('--regenerate-check', action='store_true')
    args = parser.parse_args()
    manifest = inputs()
    if args.generate or args.regenerate_check:
        palette, offsets, data, pixels = raster(manifest)
        raw = rust_source(palette, offsets, data)
        payload = struct.pack('<32H', *palette) + struct.pack('<321H', *offsets) + data
        if args.generate:
            OUTPUT.write_bytes(raw)
            manifest.update(generator_sha256=digest(Path(__file__).read_bytes()), generated_sha256=digest(raw),
                            rle_bytes=len(data), palette_bytes=64, row_table_bytes=642,
                            payload_bytes=len(payload), payload_sha256=digest(payload), raw565_sha256=digest(pixels))
            MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
        else:
            require(raw == OUTPUT.read_bytes() and digest(pixels) == manifest['raw565_sha256'], 'regeneration differs')
    check(manifest)
    print(f"Wallpaper PASS: 240x320, 16 colors, {manifest['payload_bytes']} RO bytes, 0 persistent decode-buffer bytes"
          + ('; pinned regeneration' if args.regenerate_check else '; offline binding' if args.check else '; generated'))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, OSError, ImportError, json.JSONDecodeError) as error:
        print(f'Wallpaper generation failed: {error}', file=sys.stderr)
        sys.exit(1)
