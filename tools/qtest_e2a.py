#!/usr/bin/env python3
"""Deterministic register/IRQ/reset checks of the explicit E2A contract."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import time

from qemu_control import Qmp, stop_process
from smoke_e2a import qemu_version
from qtest_pxa import (QTest, equal, prepare_timer, advance_ticks, test_uart,
                       test_frequency, test_w1c_isolation, test_rollover,
                       snapshot, TIMER, OSCR, OSSR, OIER, ICIP, ICMR, ICLR,
                       ICFP, ICPR, TIMER_IRQ)

ROOT = Path(__file__).resolve().parents[1]
HZ = 3_686_400
MACHINE = "crosshair-blueangel-e2a"


class ObservedQTest(QTest):
    def __init__(self, *args):
        super().__init__(*args)
        self.events = []
        self.levels = [0, 0]

    def request(self, command):
        self.transcript.write(f"> {command}\n")
        self.transcript.flush()
        self.stream.write(command.encode("ascii") + b"\n")
        while True:
            raw = self.stream.readline()
            if not raw:
                raise RuntimeError(f"QTest closed: {command}")
            response = raw.decode("ascii").strip()
            self.transcript.write(f"< {response}\n")
            self.transcript.flush()
            if response.startswith("IRQ "):
                _, action, number = response.split()
                irq = int(number)
                if irq >= len(self.levels):
                    raise AssertionError(f"unexpected IRQ output {irq}")
                self.levels[irq] = int(action == "raise")
                self.events.append([action, irq])
                continue
            if not (response == "OK" or response.startswith("OK ")):
                raise RuntimeError(f"QTest {command}: {response}")
            return response.split()[1:]

    def lines(self, expected, label):
        # Drain notifications generated by the previous transaction as well.
        self.readl(ICMR)
        equal(self.levels, expected, label)


def test_irq_transitions(q):
    prepare_timer(q)
    q.request("irq_intercept_out /machine/e2a sysbus-irq")
    q.lines([0, 0], "initial CPU IRQ/FIQ low")
    q.writel(TIMER, 4096)
    advance_ticks(q, HZ, 4097)
    equal(q.readl(OSSR), 0, "disabled OIER suppresses match status")
    equal(q.readl(ICPR), 0, "OIER suppresses raw PIC line")
    q.lines([0, 0], "disabled timer does not assert CPU line")
    q.writel(OIER, 1)
    equal(q.readl(OSSR), 0, "late OIER does not recreate missed match")
    equal(q.readl(ICPR), 0, "late enable leaves raw PIC low")
    q.writel(TIMER, q.readl(OSCR) + 4096)
    advance_ticks(q, HZ, 4097)
    equal(q.readl(OSSR), 1, "enabled match latches status")
    equal(q.readl(ICPR), TIMER_IRQ, "new enabled match reaches PIC")
    q.lines([0, 0], "PIC mask holds CPU IRQ low")
    q.writel(ICMR, TIMER_IRQ)
    q.lines([1, 0], "unmask raises actual IRQ output")
    q.writel(ICLR, TIMER_IRQ)
    q.lines([0, 1], "route moves actual line IRQ to FIQ")
    equal(q.readl(ICIP), 0, "IRQ pending after FIQ route")
    equal(q.readl(ICFP), TIMER_IRQ, "FIQ pending after route")
    q.writel(ICMR, 0)
    q.lines([0, 0], "mask lowers FIQ output")
    equal(q.readl(ICPR), TIMER_IRQ, "mask preserves raw source")
    q.writel(ICMR, TIMER_IRQ)
    q.lines([0, 1], "unmask reasserts FIQ")
    q.writel(OIER, 0)
    q.lines([0, 1], "OIER disable preserves already latched IRQ")
    equal(q.readl(OSSR), 1, "OIER disable preserves status latch")
    q.writel(OIER, 1)
    q.lines([0, 1], "OIER reenable preserves latched line")
    q.writel(OSSR, 0)
    q.lines([0, 1], "W1C zero preserves line")
    q.writel(OSSR, 2)
    q.lines([0, 1], "unrelated W1C preserves line")
    q.writel(OSSR, 1)
    q.lines([0, 0], "W1C lowers actual line")
    equal(q.readl(ICPR), 0, "W1C clears PIC raw pending")
    expected = [["raise", 0], ["lower", 0], ["raise", 1], ["lower", 1],
                ["raise", 1], ["lower", 1]]
    equal(q.events, expected, "exact IRQ/FIQ transition sequence")
    return {"result": "PASS", "outputs": {"0": "CPU IRQ", "1": "CPU FIQ"}, "events": q.events.copy()}


def test_reset(q, qmp):
    prepare_timer(q)
    q.writel(TIMER, 4096)
    q.writel(TIMER + 4, 65536)  # A pending future callback must be cancelled.
    q.writel(OIER, 3)
    q.writel(ICMR, TIMER_IRQ)
    q.writel(ICLR, TIMER_IRQ)
    advance_ticks(q, HZ, 4097)
    q.lines([0, 1], "reset probe starts with active FIQ")
    before = snapshot(q)
    equal(before["OSSR"], 1, "reset starts with latched source")
    virtual_before = q.step(0)
    qmp.request("system_reset")
    deadline = time.monotonic() + 3
    while q.readl(ICMR) != 0:
        if time.monotonic() > deadline:
            raise TimeoutError("E2A reset did not complete")
        time.sleep(0.01)
    q.lines([0, 0], "reset deasserts both physical outputs")
    after = snapshot(q)
    equal(after, {key: 0 for key in before}, "all implemented timer/PIC state resets")
    equal([q.readl(TIMER + i*4) for i in range(4)], [0]*4, "all four compare values reset")
    equal(q.step(0), virtual_before, "reset consumes no virtual time")
    # Re-enable without changing any compare/deadline. A forgotten old
    # callback would now latch a visible event, so OIER cannot hide it.
    q.writel(OIER, 3)
    q.writel(ICMR, TIMER_IRQ | (TIMER_IRQ << 1))
    advance_ticks(q, HZ, 65537)
    equal(q.readl(OSSR), 0, "pre-reset timer callbacks are cancelled")
    equal(q.readl(ICPR), 0, "no stale interrupt after reset")
    q.lines([0, 0], "no stale line after old deadline")
    # The peripheral remains usable after a reset, including exception source.
    prepare_timer(q)
    q.writel(TIMER, 4096)
    q.writel(OIER, 1)
    q.writel(ICMR, TIMER_IRQ)
    advance_ticks(q, HZ, 4097)
    q.lines([1, 0], "new timer IRQ works after reset")
    q.writel(OSSR, 1)
    q.lines([0, 0], "new timer IRQ acknowledges after reset")
    return {"result": "PASS", "before": before, "after": after,
            "old_deadline_cancelled": True, "post_reset_irq_tested": True}


def test_invalid_side_effects(q, stderr):
    prepare_timer(q)
    q.writel(ICMR, 0x04000000)
    before = snapshot(q)
    # QTest's readl/writel protocol hides MemTxResult. These accesses check
    # side effects/logs only; smoke_e2a independently requires CPU data aborts.
    q.readl(TIMER + 0x20)
    q.writel(ICIP, 0xffffffff)
    q.readb(OSCR)
    equal(snapshot(q), before, "invalid MMIO cannot mutate implemented state")
    log = stderr.read_text()
    if "crosshair-e2a" not in log:
        raise AssertionError("missing explicit E2A invalid-MMIO diagnostic")
    return {"result": "PASS", "state_unchanged": True,
            "transaction_error_observation": "TCG data-abort tests in smoke_e2a.py; QTest alone does not expose MemTxResult"}


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--qemu", default=os.environ.get("QEMU_BLUEANGEL", str(ROOT / "local/qemu-blueangel/bin/qemu-system-arm")))
    args = parser.parse_args()
    out = ROOT / "target/artifacts/e2a-qtest"
    out.mkdir(parents=True, exist_ok=True)
    (out / "result.json").unlink(missing_ok=True)
    serial, stderr = out / "qemu-uart.log", out / "qemu-stderr.log"
    result = {"result": "FAIL", "machine": MACHINE,
              "scope": "register-level synthetic subset; no guest instructions in QTest, no physical HTC traces",
              "qemu_version": qemu_version(args.qemu),
              "qemu_sha256": hashlib.sha256(Path(shutil.which(args.qemu) or args.qemu).read_bytes()).hexdigest()}
    with tempfile.TemporaryDirectory(prefix="crosshair-e2a-qtest-") as temp:
        qmp_path, qtest_path = Path(temp) / "qmp", Path(temp) / "qtest"
        command = [args.qemu, "-machine", MACHINE, "-accel", "qtest", "-S", "-display", "none",
                   "-monitor", "none", "-serial", f"file:{serial}", "-nic", "none", "-d", "guest_errors",
                   "-qmp", f"unix:{qmp_path},server=on,wait=off",
                   "-qtest", f"unix:{qtest_path},server=on,wait=off", "-qtest-log", str(out / "qemu-qtest.log")]
        result["command"] = command
        with stderr.open("wb") as err, (out / "protocol.log").open("w") as transcript:
            process = subprocess.Popen(command, stdout=subprocess.DEVNULL, stderr=err, stdin=subprocess.DEVNULL)
            qmp = q = None
            try:
                qmp = Qmp(qmp_path, process)
                q = ObservedQTest(qtest_path, process, transcript)
                qmp.request("cont")  # Device callback dispatch, dummy QTest CPU.
                result["cpu_before"] = qmp.monitor("info registers")
                result["uart"] = test_uart(q, serial)
                result["frequency"] = test_frequency(q, HZ)
                result["irq_transitions"] = test_irq_transitions(q)
                result["w1c_isolation"] = test_w1c_isolation(q, HZ)
                result["counter_rollover"] = test_rollover(q, HZ)
                result["reset"] = test_reset(q, qmp)
                result["invalid_mmio"] = test_invalid_side_effects(q, stderr)
                result["cpu_after"] = qmp.monitor("info registers")
                # Reset may change PC to reset vector 0; neither path executes
                # guest instructions (dummy CPU, as in the accepted E1 test).
                result["result"] = "PASS"
                qmp.request("quit")
                process.wait(timeout=3)
                equal(process.returncode, 0, "QEMU clean exit")
            except Exception as error:
                result["result"] = "FAIL"
                result["error"] = f"{type(error).__name__}: {error}"
                raise
            finally:
                try:
                    if q:
                        q.close()
                    if qmp:
                        qmp.close()
                    stop_process(process)
                except Exception as error:
                    result["result"] = "FAIL"
                    result["cleanup_error"] = f"{type(error).__name__}: {error}"
                    raise
                finally:
                    (out / "result.json").write_text(json.dumps(result, indent=2) + "\n")
    print("PASS E2A QTest: UART, exact frequency, IRQ/FIQ transitions, W1C, rollover, full reset, invalid-MMIO side effects")


if __name__ == "__main__":
    main()
