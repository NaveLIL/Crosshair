#!/usr/bin/env python3
"""Deterministically normalize the pinned MIT Cozette subset into 8x13 rows.

No font parser runs before the exact input length/SHA gate. A supplied input
is read-only; without --input the one pinned release asset is fetched. The
full upstream BDF is never copied into the source tree by this tool.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import urllib.request

URL = 'https://github.com/the-moonwitch/Cozette/releases/download/v.1.30.0/cozette.bdf'
SHA256 = '8d740166af3a14053773ac7a8846bf288c8818a44f73ab28d4725d91b03a5639'
SIZE = 683147
CODEPOINTS = sorted(set(range(0x20, 0x7f)) | set(range(0x410, 0x450)) |
                    {0x401, 0x451, 0x2014, 0xfffd})
ROOT = Path(__file__).resolve().parents[1]


def read_source(path):
    if path is None:
        request = urllib.request.Request(URL, headers={'User-Agent': 'Crosshair-font-subset'})
        with urllib.request.urlopen(request, timeout=30) as source:
            data = source.read(SIZE + 1)
    else:
        flags = os.O_RDONLY | getattr(os, 'O_NONBLOCK', 0)
        with os.fdopen(os.open(path, flags), 'rb') as source:
            if not stat.S_ISREG(os.fstat(source.fileno()).st_mode):
                raise ValueError('input must be a regular file')
            data = source.read(SIZE + 1)
    if len(data) != SIZE or hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError('font length/SHA-256 does not match the pinned Cozette BDF')
    return data


def generate(data):
    glyphs = {}
    for block in re.findall(r'^STARTCHAR (.*?)^ENDCHAR$', data.decode('ascii'), re.M | re.S):
        encoding = re.search(r'^ENCODING (\d+)$', block, re.M)
        if encoding is None:
            raise ValueError('BDF glyph without an encoding')
        code = int(encoding[1])
        if code not in CODEPOINTS:
            continue
        if code in glyphs:
            raise ValueError('duplicate selected BDF glyph')
        width, height, left, bottom = map(int, re.search(r'^BBX ([\d -]+)$', block, re.M)[1].split())
        if tuple(map(int, re.search(r'^DWIDTH ([\d -]+)$', block, re.M)[1].split())) != (6, 0):
            raise ValueError('selected glyph does not have the expected advance')
        rows = block.split('\nBITMAP\n', 1)[1].strip().splitlines()
        if len(rows) != height or not 0 < width <= 8 or not 0 < height <= 13:
            raise ValueError('invalid selected glyph bitmap size')
        output = [0] * 13
        for row, encoded in enumerate(rows):
            bits = int(encoded, 16)
            bit_count = len(encoded) * 4
            for col in range(width):
                if bits & (1 << (bit_count - col - 1)):
                    x, y = left + col, 10 - bottom - height + row
                    if not (0 <= x < 8 and 0 <= y < 13):
                        raise ValueError('ink would be clipped by the normalized glyph cell')
                    output[y] |= 0x80 >> x
        glyphs[code] = output
    if sorted(glyphs) != CODEPOINTS:
        raise ValueError('missing selected glyphs')
    lines = [
        '// Generated by ui/tools/subset_font.py; do not edit bitmap rows by hand.',
        '// Cozette v.1.30.0, copyright (c) 2020 Ines <ines@moonwit.ch>, MIT.',
        '// Full original notice: ui/third_party/cozette/LICENSE.',
        '// Source SHA-256: ' + SHA256,
        '// Normalized ink: MSB is x=0; 8 pixels x 13 rows; advance remains 6.',
        '#![allow(clippy::unreadable_literal)]',
        'pub const HEIGHT: usize = 13;',
        'pub const ADVANCE: usize = 6;',
        'pub const LINE_HEIGHT: usize = 14;',
        'pub const GLYPH_COUNT: usize = 163;',
        '#[rustfmt::skip]',
        'pub const CODEPOINTS: [u32; GLYPH_COUNT] = [',
    ]
    lines.extend('    ' + ', '.join(f'0x{c:04x}' for c in CODEPOINTS[i:i+8]) + ','
                 for i in range(0, len(CODEPOINTS), 8))
    lines += ['];', '#[rustfmt::skip]', 'static ROWS: [[u8; HEIGHT]; GLYPH_COUNT] = [']
    for code in CODEPOINTS:
        rows = ', '.join(f'0x{x:02x}' for x in glyphs[code])
        lines.append(f'    [{rows}], // U+{code:04X}')
    lines += ['];', '',
              'pub fn glyph(character: char) -> Option<&\'static [u8; HEIGHT]> {',
              '    CODEPOINTS',
              '        .binary_search(&(character as u32))',
              '        .ok()',
              '        .map(|index| &ROWS[index])',
              '}', '',
              'pub fn replacement() -> &\'static [u8; HEIGHT] {',
              f'    &ROWS[{CODEPOINTS.index(0xfffd)}]',
              '}', '']
    return '\n'.join(lines).encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path)
    parser.add_argument('--output', type=Path, default=ROOT / 'src/font.rs')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        if args.input is not None and args.input.resolve() == args.output.resolve():
            raise ValueError('output must differ from the read-only input')
        data = generate(read_source(args.input))
        if args.check:
            if args.output.read_bytes() != data:
                raise ValueError('generated subset differs from committed source')
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(data)
    except (OSError, ValueError) as error:
        parser.exit(1, f'error: {error}\n')
    print(json.dumps({'glyphs': len(CODEPOINTS), 'bitmap_bytes': len(CODEPOINTS) * 13,
                      'generated_sha256': hashlib.sha256(data).hexdigest(), 'check': args.check}))


if __name__ == '__main__':
    main()
